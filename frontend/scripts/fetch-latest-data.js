/**
 * Build-time script to fetch latest data from server
 * and update the defaultData.ts file
 * 
 * Run this before deployment or on a schedule
 * Usage: node scripts/fetch-latest-data.js
 */

const fs = require('fs');
const path = require('path');

const API_URL = process.env.NEXT_PUBLIC_API_URL || 'https://portfolio-website-i30p.onrender.com/api';
const OUTPUT_FILE = path.join(__dirname, '../app/utils/defaultData.ts');

// Retry fetch with exponential backoff
async function fetchWithRetry(url, retries = 5, delay = 4000) {
    for (let i = 0; i < retries; i++) {
        try {
            console.log(`Fetching ${url} (attempt ${i + 1}/${retries})...`);
            const response = await fetch(url, {
                signal: AbortSignal.timeout(30000) // 30s timeout
            });

            if (!response.ok) {
                throw new Error(`HTTP ${response.status}`);
            }

            return await response.json();
        } catch (error) {
            console.warn(`Attempt ${i + 1} failed:`, error.message);

            if (i < retries - 1) {
                console.log(`Retrying in ${delay}ms...`);
                await new Promise(resolve => setTimeout(resolve, delay));
                delay *= 1.5; // Exponential backoff
            } else {
                throw error;
            }
        }
    }
}

// Fetch all portfolio data
async function fetchAllData() {
    console.log('\n🚀 Fetching latest portfolio data from server...\n');

    const endpoints = ['profile', 'about', 'skills', 'tools', 'projects', 'certifications', 'blog'];
    const results = {};

    for (const endpoint of endpoints) {
        try {
            const data = await fetchWithRetry(`${API_URL}/${endpoint}`);
            results[endpoint] = data;
            console.log(`✅ ${endpoint}: Success`);
        } catch (error) {
            console.error(`❌ ${endpoint}: Failed - ${error.message}`);
            results[endpoint] = null;
        }
    }

    return results;
}

// Generate TypeScript file content
function generateTypeScriptFile(data) {
    const timestamp = new Date().toISOString();

    return `// Auto-generated default data from latest server fetch
// Last updated: ${timestamp}
// DO NOT EDIT MANUALLY - This file is auto-generated by scripts/fetch-latest-data.js

export const DEFAULT_DATA = ${JSON.stringify({
        profile: data.profile || null,
        about: data.about || null,
        skills: data.skills || [],
        tools: data.tools || [],
        projects: data.projects || [],
        certifications: data.certifications || [],
        blogs: data.blog || []
    }, null, 2)};

export const LAST_FETCHED = '${timestamp}';

// Check if data is default/loading state
export const isDefaultData = (data: any, type: string): boolean => {
  if (!data) return true;
  
  switch (type) {
    case 'projects':
      return Array.isArray(data) && data.length === 0;
    case 'certifications':
      return Array.isArray(data) && data.length === 0;
    case 'blogs':
      return Array.isArray(data) && data.length === 0;
    default:
      return false;
  }
};
`;
}

// Main execution
async function main() {
    try {
        console.log('📦 Portfolio Data Fetch Script');
        console.log('================================\n');
        console.log(`API URL: ${API_URL}\n`);

        // Fetch all data
        const data = await fetchAllData();

        // Check if we got any data
        const successCount = Object.values(data).filter(v => v !== null).length;

        if (successCount === 0) {
            console.error('\n❌ Failed to fetch any data from server!');
            console.error('⚠️  Keeping existing defaultData.ts unchanged');
            process.exit(1);
        }

        console.log(`\n📊 Successfully fetched ${successCount}/7 endpoints`);

        // Generate new TypeScript file
        const fileContent = generateTypeScriptFile(data);

        // Write to file
        fs.writeFileSync(OUTPUT_FILE, fileContent, 'utf8');

        console.log(`\n✅ Updated ${OUTPUT_FILE}`);
        console.log(`\n🎉 Success! Default data is now up-to-date with server.`);
        console.log(`\n💡 Next steps:`);
        console.log(`   1. Commit the updated defaultData.ts`);
        console.log(`   2. Deploy to Hostinger`);
        console.log(`   3. New users will see this data instantly!\n`);

    } catch (error) {
        console.error('\n💥 Fatal error:', error);
        process.exit(1);
    }
}

// Run if called directly
if (require.main === module) {
    main();
}

module.exports = { fetchAllData, generateTypeScriptFile };
